#!/usr/bin/env python3
"""build918_919.py - splice BEATS 918-919 (Toby, Sept 27, 7:12 PM) into the game."""
import io
GAME = '/Users/tdeshane/endless-staircase/index.html'
src = io.open(GAME, encoding='utf-8').read()
orig = src

OLD_CYC, NEW_CYC = '19916.0', '19960.0'
assert src.count('const LV_CYC = %s;' % OLD_CYC) == 1
src = src.replace('const LV_CYC = %s;' % OLD_CYC, 'const LV_CYC = %s;' % NEW_CYC, 1)

ROWS = io.open('/Users/tdeshane/endless-staircase/tools/rows918_919.txt', encoding='utf-8').read().rstrip('\n')
# anchor: the last LV_BEATS row, beat 917
anchor_row = [l for l in src.split('\n') if l.startswith('  { key:"THE ONLY ONE WHO CONSUMES DATA"')]
assert len(anchor_row) == 1
i = src.index(anchor_row[0])
j = src.index('" },', i) + len('" },')
src = src[:j] + '\n' + ROWS + src[j:]

SEG = io.open('/Users/tdeshane/endless-staircase/tools/segs918_919.txt', encoding='utf-8').read().rstrip('\n')
anchor_seg = '  if(c >= 19894.0 && c < 19916.0) return [917, c-19894.0];  // THE ONLY ONE WHO CONSUMES DATA'
assert src.count(anchor_seg) == 1
src = src.replace(anchor_seg, SEG + '\n' + anchor_seg, 1)

BRANCH = io.open('/Users/tdeshane/endless-staircase/tools/branches918_919.js', encoding='utf-8').read()
anchor_br = '  } else if(ph===814){'
assert src.count(anchor_br) == 1
src = src.replace(anchor_br, BRANCH + anchor_br, 1)

assert src != orig
io.open(GAME, 'w', encoding='utf-8').write(src)
print('OK: LV_CYC %s -> %s, 2 rows, 2 seg lines, 2 branches' % (OLD_CYC, NEW_CYC))
